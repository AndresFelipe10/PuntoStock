<?php

namespace Tests\Feature\Superadmin;

use App\Mail\DailyBusinessSummaryMail;
use App\Mail\WelcomeTenantMail;
use App\Models\Business;
use App\Models\Role;
use App\Models\User;
use Illuminate\Foundation\Testing\RefreshDatabase;
use Illuminate\Support\Facades\Hash;
use Illuminate\Support\Facades\Mail;
use Tests\TestCase;

class SuperadminBusinessUserTest extends TestCase
{
    use RefreshDatabase;

    protected User $superadmin;
    protected User $normalUser;
    protected Business $business;
    protected Role $adminRole;
    protected Role $employeeRole;

    protected function setUp(): void
    {
        parent::setUp();

        $this->adminRole = Role::create([
            'name' => 'Administrador',
            'slug' => Role::ROLE_ADMIN,
        ]);

        $this->employeeRole = Role::create([
            'name' => 'Empleado',
            'slug' => Role::ROLE_EMPLOYEE,
        ]);

        $this->superadmin = User::factory()->create([
            'is_superadmin' => true,
            'must_change_password' => false,
        ]);

        $this->normalUser = User::factory()->create([
            'is_superadmin' => false,
            'must_change_password' => false,
        ]);

        $this->business = Business::create([
            'name' => 'Restaurante Cali Mío',
            'business_type' => 'restaurant',
            'status' => 'active',
            'is_active' => true,
        ]);
    }

    public function test_superadmin_can_view_users_create_form(): void
    {
        $response = $this->actingAs($this->superadmin)
            ->get(route('superadmin.businesses.users.create', $this->business));

        $response->assertOk();
        $response->assertSee('Agregar Colaborador');
        $response->assertSee('Restaurante Cali Mío');
        $response->assertSee('Administrador');
        $response->assertSee('Empleado');
    }

    public function test_superadmin_can_create_admin_user_for_business(): void
    {
        $response = $this->actingAs($this->superadmin)
            ->post(route('superadmin.businesses.users.store', $this->business), [
                'name' => 'Carlos Administrador',
                'email' => 'carlos.admin@puntostock.co',
                'role' => 'admin',
                'password' => 'Temporal123!',
            ]);

        $response->assertRedirect(route('superadmin.businesses.users', $this->business));
        $response->assertSessionHas('temp_password', 'Temporal123!');
        $response->assertSessionHas('created_user_email', 'carlos.admin@puntostock.co');

        $newUser = User::where('email', 'carlos.admin@puntostock.co')->first();
        $this->assertNotNull($newUser);
        $this->assertEquals('Carlos Administrador', $newUser->name);
        $this->assertTrue((bool) $newUser->must_change_password);
        $this->assertFalse((bool) $newUser->is_superadmin);
        $this->assertTrue(Hash::check('Temporal123!', $newUser->password));

        $this->assertDatabaseHas('business_user', [
            'business_id' => $this->business->id,
            'user_id' => $newUser->id,
            'role_id' => $this->adminRole->id,
            'is_active' => true,
        ]);
    }

    public function test_superadmin_can_create_employee_user_for_business_with_autogenerated_password(): void
    {
        $response = $this->actingAs($this->superadmin)
            ->post(route('superadmin.businesses.users.store', $this->business), [
                'name' => 'Marta Mesera',
                'email' => 'marta.mesera@puntostock.co',
                'role' => 'employee',
                'password' => '', // Dejar vacío para autogenerar
            ]);

        $response->assertRedirect(route('superadmin.businesses.users', $this->business));
        $response->assertSessionHas('temp_password');

        $tempPassword = session('temp_password');
        $this->assertNotEmpty($tempPassword);
        $this->assertGreaterThanOrEqual(16, strlen($tempPassword));

        $newUser = User::where('email', 'marta.mesera@puntostock.co')->first();
        $this->assertNotNull($newUser);
        $this->assertEquals('Marta Mesera', $newUser->name);
        $this->assertTrue((bool) $newUser->must_change_password);
        $this->assertFalse((bool) $newUser->is_superadmin);
        $this->assertTrue(Hash::check($tempPassword, $newUser->password));

        $this->assertDatabaseHas('business_user', [
            'business_id' => $this->business->id,
            'user_id' => $newUser->id,
            'role_id' => $this->employeeRole->id,
            'is_active' => true,
        ]);
    }

    public function test_email_must_be_globally_unique_in_users_table(): void
    {
        User::factory()->create([
            'email' => 'existente@puntostock.co',
        ]);

        $response = $this->actingAs($this->superadmin)
            ->from(route('superadmin.businesses.users.create', $this->business))
            ->post(route('superadmin.businesses.users.store', $this->business), [
                'name' => 'Duplicado User',
                'email' => 'existente@puntostock.co',
                'role' => 'employee',
            ]);

        $response->assertRedirect(route('superadmin.businesses.users.create', $this->business));
        $response->assertSessionHasErrors(['email']);
    }

    public function test_non_superadmin_cannot_access_collaborator_creation_routes(): void
    {
        $response = $this->actingAs($this->normalUser)
            ->get(route('superadmin.businesses.users.create', $this->business));

        $response->assertNotFound();

        $postResponse = $this->actingAs($this->normalUser)
            ->post(route('superadmin.businesses.users.store', $this->business), [
                'name' => 'Intruso',
                'email' => 'intruso@puntostock.co',
                'role' => 'employee',
            ]);

        $postResponse->assertNotFound();
    }

    public function test_superadmin_views_render_responsive_offcanvas_sidebar_and_table_structure(): void
    {
        $response = $this->actingAs($this->superadmin)
            ->get(route('superadmin.businesses.index'));

        $response->assertOk();
        $response->assertSee('id="superadminSidebar"', false);
        $response->assertSee('data-bs-toggle="offcanvas"', false);
        $response->assertSee('data-bs-target="#superadminSidebar"', false);
        $response->assertSee('class="table-responsive"', false);
        $response->assertSee('btn-action-table', false);
        $response->assertSee('Crear Nuevo Negocio', false);
    }

    public function test_superadmin_creates_employee_with_manual_password_sends_welcome_mail(): void
    {
        Mail::fake();

        $response = $this->actingAs($this->superadmin)
            ->post(route('superadmin.businesses.users.store', $this->business), [
                'name' => 'Sara Vendedora',
                'email' => 'sara.vendedora@puntostock.co',
                'role' => 'employee',
                'password' => 'ManualPass123!',
            ]);

        $response->assertRedirect(route('superadmin.businesses.users', $this->business));
        $response->assertSessionHas('temp_password', 'ManualPass123!');

        $newUser = User::where('email', 'sara.vendedora@puntostock.co')->first();
        $this->assertNotNull($newUser);
        $this->assertTrue((bool) $newUser->must_change_password);

        Mail::assertSent(WelcomeTenantMail::class, function (WelcomeTenantMail $mail) use ($newUser) {
            $html = $mail->render();
            return $mail->hasTo('sara.vendedora@puntostock.co')
                && $mail->business->id === $this->business->id
                && $mail->adminUser->id === $newUser->id
                && $mail->plainPassword === 'ManualPass123!'
                && $mail->role === 'employee'
                && $mail->isNewBusiness === false
                && str_contains($html, 'Empleado / Colaborador')
                && str_contains($html, 'ManualPass123!')
                && str_contains($html, 'Tu cuenta de usuario ha sido vinculada');
        });
    }

    public function test_superadmin_creates_employee_with_autogenerated_password_sends_welcome_mail(): void
    {
        Mail::fake();

        $response = $this->actingAs($this->superadmin)
            ->post(route('superadmin.businesses.users.store', $this->business), [
                'name' => 'Jorge Bodeguero',
                'email' => 'jorge.bodega@puntostock.co',
                'role' => 'employee',
                'password' => '',
            ]);

        $response->assertRedirect(route('superadmin.businesses.users', $this->business));
        $response->assertSessionHas('temp_password');

        $tempPassword = session('temp_password');
        $this->assertNotEmpty($tempPassword);

        $newUser = User::where('email', 'jorge.bodega@puntostock.co')->first();
        $this->assertNotNull($newUser);
        $this->assertTrue((bool) $newUser->must_change_password);

        Mail::assertSent(WelcomeTenantMail::class, function (WelcomeTenantMail $mail) use ($newUser, $tempPassword) {
            return $mail->hasTo('jorge.bodega@puntostock.co')
                && $mail->business->id === $this->business->id
                && $mail->adminUser->id === $newUser->id
                && $mail->plainPassword === $tempPassword
                && $mail->role === 'employee'
                && $mail->isNewBusiness === false;
        });
    }

    public function test_collaborator_first_login_redirects_to_password_change(): void
    {
        $response = $this->actingAs($this->superadmin)
            ->post(route('superadmin.businesses.users.store', $this->business), [
                'name' => 'Lucía Cajera',
                'email' => 'lucia.cajera@puntostock.co',
                'role' => 'employee',
                'password' => 'Temporal123!',
            ]);

        $response->assertRedirect(route('superadmin.businesses.users', $this->business));

        // Cerrar sesión del superadministrador
        auth()->logout();

        // Iniciar sesión como la colaboradora recién creada
        $loginResponse = $this->post('/login', [
            'email' => 'lucia.cajera@puntostock.co',
            'password' => 'Temporal123!',
        ]);

        $loginResponse->assertRedirect(route('password.change'));
        $this->assertAuthenticated();
        $this->assertEquals('lucia.cajera@puntostock.co', auth()->user()->email);
        $this->assertTrue((bool) auth()->user()->must_change_password);
    }

    public function test_nightly_summary_command_never_sends_report_to_employee_users(): void
    {
        Mail::fake();

        // Negocio con suscripción activa y reporte habilitado, pero SOLO con usuario empleado
        $bizEmployeeOnly = Business::create([
            'name' => 'Comercio Solo Empleados',
            'business_type' => 'retail',
            'email' => 'empresa.general@puntostock.co',
            'is_active' => true,
            'nightly_report_enabled' => true,
        ]);

        $employeeUser = User::factory()->create([
            'email' => 'empleado.estricto@puntostock.co',
            'is_superadmin' => false,
        ]);

        $bizEmployeeOnly->users()->attach($employeeUser->id, [
            'role_id' => $this->employeeRole->id,
            'is_active' => true,
        ]);

        $this->artisan('pos:send-daily-summary')
            ->assertExitCode(0);

        // Se envía al email corporativo de la empresa, NUNCA al email del empleado
        Mail::assertSent(DailyBusinessSummaryMail::class, function ($mail) use ($bizEmployeeOnly) {
            return $mail->hasTo('empresa.general@puntostock.co')
                && $mail->business->id === $bizEmployeeOnly->id;
        });

        Mail::assertNotSent(DailyBusinessSummaryMail::class, function ($mail) {
            return $mail->hasTo('empleado.estricto@puntostock.co');
        });
    }
}
